/* ── STROOP ── */
CATS.stroop = {
  name: 'Тест Струпа',
  desc: 'Определи цвет или значение слова',
  icon: '🎨',
  bg: '#eeedfe',
  fg: '#3c3489',

  gen() {
    const lvl = getLvl();


    /* ─────────────────────────────
       ЦВЕТА ПО УРОВНЯМ

       Единственная ось сложности —
       размер палитры. Чем больше
       цветов, тем труднее выбрать
       из вариантов и тем ближе
       могут быть похожие оттенки.

       1 — 4 цвета
       2 — 7 цветов
       3 — 10 цветов
       4 — 12 цветов
       ───────────────────────────── */

    const C4 = [
      'красный',
      'синий',
      'жёлтый',
      'зелёный'
    ];

    const C7 = [
      ...C4,
      'оранжевый',
      'голубой',
      'фиолетовый'
    ];

    const C10 = [
      ...C7,
      'розовый',
      'коричневый',
      'бордовый'
    ];

    const C12 = [
      ...C10,
      'серый',
      'чёрный'
    ];

    let pool;

    switch (lvl.id) {
      case 1:
        pool = C4;
        break;

      case 2:
        pool = C7;
        break;

      case 3:
        pool = C10;
        break;

      default:
        pool = C12;
        break;
    }


    /* ─────────────────────────────
       СТАНДАРТНЫЕ ЦВЕТА
       ───────────────────────────── */

    const K = {
      красный:     '#FF0000',
      синий:       '#0000FF',
      жёлтый:      '#FFFF00',
      зелёный:     '#008000',

      оранжевый:   '#FFA500',
      голубой:     '#00BFFF',
      фиолетовый:  '#800080',

      розовый:     '#FFC0CB',
      коричневый:  '#A52A2A',
      бордовый:    '#800000',

      серый:       '#808080',
      чёрный:      '#000000'
    };


    /* ─────────────────────────────
       СЛОВО
       ───────────────────────────── */

    const word = pick(pool);


    /* ─────────────────────────────
       ЦВЕТ ШРИФТА

       10% — совпадает со словом
       90% — отличается
       ───────────────────────────── */

    const wordInkMatch = Math.random() < 0.10;

    const ink = wordInkMatch
      ? word
      : pick(
          pool.filter(c => c !== word)
        );


    /* ─────────────────────────────
       ТИП ВОПРОСА — 50 / 50
       ───────────────────────────── */

    const askInk = Math.random() < 0.5;

    const question = askInk
      ? 'Каким <b>цветом</b> написано слово?'
      : 'Какой <b>цвет обозначает</b> это слово?';


    /* ─────────────────────────────
       ПРАВИЛЬНЫЙ ОТВЕТ
       ───────────────────────────── */

    const answer = askInk
      ? ink
      : word;


    /* ─────────────────────────────
       ОТОБРАЖЕНИЕ СЛОВА

       Одинаково на всех уровнях
       (как раньше выглядел уровень 2):
       обычный жирный Arial, без смены
       шрифта и без цветного фона.
       Сложность даёт только palette
       (больше цветов — труднее выбрать).
       ───────────────────────────── */

    const wordHtml = `
      <span style="
        display:inline-block;
        font-family:Arial, sans-serif !important;
        font-weight:700 !important;
        font-size:46px !important;
        line-height:1.15;
        color:${K[ink]} !important;
      ">
        ${word}
      </span>
    `;

    const vis = wordHtml;


    /* ─────────────────────────────
       ВАРИАНТЫ ОТВЕТОВ

       Всегда 4 кнопки.
       Гарантированно попадают:
         - правильный ответ (answer)
         - цвет чернил (ink) — самый заметный
           "отвлекающий" вариант
         - слово-значение (word) — второй
           "острый" вариант
       Остальное — случайные филлеры до 4 штук.
       ───────────────────────────── */

    const guaranteed = new Set([answer, ink, word]);

    const fillers = shu(
      pool.filter(c => !guaranteed.has(c))
    );

    let fi = 0;
    while (guaranteed.size < 4 && fi < fillers.length) {
      guaranteed.add(fillers[fi]);
      fi++;
    }

    const options = shu([...guaranteed]);


    /* ─────────────────────────────
       РЕЗУЛЬТАТ
       ───────────────────────────── */

    return {
      q: question,
      vis: vis,
      ans: answer,
      opts: options
    };
  }
};
