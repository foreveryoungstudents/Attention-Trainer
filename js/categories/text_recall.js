/* ───────── Вспомогательные ───────── */
const trWords = s => s.toLowerCase().replace(/ё/g, 'е').replace(/[^а-яa-z0-9\s]/g, ' ').split(/\s+/).filter(Boolean);
const trEsc = s => s.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// возвращает { ok, hit, total }
function trCheck(item, input) {
  const padded = ' ' + trWords(input).join(' ') + ' ';
  const hits = item.keys.map(group => group.some(raw => {
    const s = raw.toLowerCase().replace(/ё/g, 'е');
    return /^\d+$/.test(s) ? padded.includes(' ' + s + ' ') : padded.includes(' ' + s);
  }));
  const hit = hits.filter(Boolean).length;
  return { ok: hit === item.keys.length, hit, total: item.keys.length };
}

function trHighlight(item) {
  let html = trEsc(item.text);
  (item.hl || []).forEach(h => {
    const e = trEsc(h);
    if (html.includes(e)) html = html.replace(e, `<mark class="tr-hl">${e}</mark>`);
  });
  return html;
}

